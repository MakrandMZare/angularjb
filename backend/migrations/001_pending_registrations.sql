CREATE TABLE IF NOT EXISTS pending_registrations (
  registration_id CHAR(36) NOT NULL,
  username VARCHAR(80) NOT NULL,
  email VARCHAR(254) NOT NULL,
  mobile VARCHAR(32) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  email_otp_hash CHAR(60) DEFAULT NULL,
  email_otp_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  email_otp_expires_at DATETIME DEFAULT NULL,
  email_last_sent_at DATETIME NOT NULL,
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  mobile_otp_hash CHAR(60) DEFAULT NULL,
  mobile_otp_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  mobile_otp_expires_at DATETIME DEFAULT NULL,
  mobile_last_sent_at DATETIME DEFAULT NULL,
  mobile_verified BOOLEAN NOT NULL DEFAULT FALSE,
  expires_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (registration_id),
  UNIQUE KEY uq_pending_username (username),
  UNIQUE KEY uq_pending_email (email),
  UNIQUE KEY uq_pending_mobile (mobile),
  KEY idx_pending_expires_at (expires_at)
);
